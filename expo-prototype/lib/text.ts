// ─── 表示用の文字の整え ──────────────────────────────────────────
// FAMIC の登録データ由来の名前は半角カナ（「ｻﾝｹｲ石灰硫黄合剤」「ｷｬﾍﾞﾂ」など）のまま入っている。
// 照合（作物名・農薬名の突き合わせ）はこの原文で行うので、**保存値は変えずに表示するときだけ**全角にする。
// NFKC を文字列全体にかけると全角英数や括弧まで半角になるため、半角カナの範囲だけに限る。

/** 半角カナ（U+FF61〜U+FF9F）の部分だけ全角にする。濁点・半濁点は結合される（ﾎﾞ → ボ） */
export const dispName = (s: string | null | undefined): string =>
  (s ?? "").replace(/[｡-ﾟ]+/g, m => m.normalize("NFKC"));
